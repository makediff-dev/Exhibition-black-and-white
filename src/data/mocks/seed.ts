function buildVenueDailyOccupancy(): VenueDailyOccupancy[] {
  const items: VenueDailyOccupancy[] = [];

  for (let month = 1; month <= 12; month += 1) {
    const daysInMonth = new Date(2026, month, 0).getDate();
    for (let day = 1; day <= daysInMonth; day += 1) {
      const date = `2026-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
      let percent = 18 + ((month + day) % 12);

      if (month === 3) percent = 55 + (day % 20);
      if (month === 5) percent = 42 + (day % 18);
      if (month === 11) percent = 5 + (day % 12);
      if (month === 7) percent = 28 + (day % 10);

      items.push({ date, venueId: "venue-1", percent: Math.min(percent, 95) });
    }
  }

  return items;
}

